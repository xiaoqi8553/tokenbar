"use strict";

/**
 * dashboard.html 构建脚本。
 *
 * 把 desktop/ui/** 下的源片段按 base.html 中的占位标记拼回同构单文件。
 * 纯 Node 字符串拼接、零依赖：不引入运行时框架，也不引入任何打包器。
 *
 * 用法：node scripts/build-dashboard.js
 */
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const uiDir = path.join(root, "desktop", "ui");
const outFile = path.join(root, "desktop", "dashboard.html");

const BANNER = "<!-- generated by scripts/build-dashboard.js; do not edit directly -->";

/** 占位标记 → 源片段，顺序即拼接顺序 */
const PARTS = [
  { marker: "/*__TOKENS_CSS__*/", file: "tokens.css" },
  { marker: "/*__LAYOUT_CSS__*/", file: "layout.css" },
  { marker: "<!--__LAYOUT_HTML__-->", file: "layout.html" },
  { marker: "/*__FORMAT_JS__*/", file: "format.js" },
  { marker: "/*__CHARTS_JS__*/", file: "charts.js" },
  { marker: "/*__RENDER_JS__*/", file: "render.js" },
  { marker: "/*__AUTH_PANEL_JS__*/", file: "auth-panel.js" },
  { marker: "/*__APP_JS__*/", file: "app.js" }
];

function readFromUi(file) {
  const full = path.join(uiDir, file);
  if (!fs.existsSync(full)) {
    throw new Error("缺少源片段：" + path.relative(root, full));
  }
  return fs.readFileSync(full, "utf8");
}

let html = readFromUi("base.html");
if (!html.startsWith(BANNER)) {
  throw new Error("base.html 顶部缺少生成标记：" + BANNER);
}

for (const { marker, file } of PARTS) {
  const hits = html.split(marker).length - 1;
  if (hits !== 1) {
    throw new Error("占位标记 " + marker + " 出现 " + hits + " 次（应为 1 次）");
  }
  const fragment = readFromUi(file);
  // 必须用函数式 replacement：片段里有大量 $("...") / $& 之类的字符，
  // 字符串 replacement 会被 String.replace 当成特殊替换模式而改写内容。
  html = html.replace(marker, () => fragment);
}

for (const { marker } of PARTS) {
  if (html.includes(marker)) {
    throw new Error("构建后仍残留占位标记：" + marker);
  }
}

fs.writeFileSync(outFile, html, "utf8");
console.log("已生成 " + path.relative(root, outFile) + "（" + Buffer.byteLength(html, "utf8") + " 字节）");
