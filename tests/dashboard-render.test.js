"use strict";

/**
 * 3.0 W4 A-E2E：dashboard.html 作为构建产物的静态契约。
 * 只做源码/产物断言，不起 Electron（窗口行为由 desktop-smoke.js 覆盖）。
 */

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { execFileSync } = require("node:child_process");
const assert = require("node:assert/strict");
const { test } = require("node:test");

const root = path.resolve(__dirname, "..");
const read = rel => fs.readFileSync(path.join(root, rel), "utf8");
const sha256 = file => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");

const html = read("desktop/dashboard.html");

test("dashboard.html 是 build-dashboard.js 的生成物，标题与美元计价锁死", () => {
  assert.ok(html.startsWith("<!-- generated by scripts/build-dashboard.js; do not edit directly -->"),
    "第一行必须是生成标记，手工改动会被下次构建覆盖");
  assert.match(html, /<title>TokenBar/);
  assert.ok(html.includes("$"), "等价花费必须用美元展示");
  assert.equal(html.includes("¥"), false, "人民币符号不应泄露到界面");
  assert.equal(html.includes("￥"), false, "全角人民币符号也不应出现");
  assert.equal(html.includes("data:image"), false, "截图不内联进单文件看板");
});

test("主题双按钮与时间区间 0/7/14/30 契约完整", () => {
  assert.ok(html.includes('id="theme-switch"'));
  assert.ok(html.includes('data-theme="light"'));
  assert.ok(html.includes('data-theme="dark"'));
  assert.ok(html.includes("月之亮面"));
  assert.ok(html.includes("月之暗面"));
  assert.ok(html.includes('id="hour-badge"'), "活跃时段徽标必须存在");
  assert.ok(html.includes('id="range"'), "区间切换容器必须存在");

  const ranges = [...html.matchAll(/\{\s*key:\s*(\d+),\s*label:/g)].map(match => match[1]);
  assert.deepEqual(ranges.sort(), ["0", "14", "30", "7"]);
  assert.ok(html.includes("RANGES.map(item"), "按钮必须由 RANGES 动态生成");
  assert.ok(html.includes('data-key="'), "按钮应带 data-key 供冒烟脚本点击");
});

test("README 引用的 5 张文档截图真实存在且非空", () => {
  const readme = read("README.md");
  assert.ok(readme.includes("srcset="), "README 应使用 srcset 做亮/暗主题截图");
  const refs = [...readme.matchAll(/docs\/shots\/([A-Za-z0-9._-]+\.png)/g)].map(match => match[1]);
  const unique = [...new Set(refs)].sort();
  assert.deepEqual(unique, [
    "auth-panel.png",
    "dashboard-dark.png",
    "dashboard-hours.png",
    "dashboard-light.png",
    "popover.png"
  ]);
  for (const name of unique) {
    const stat = fs.statSync(path.join(root, "docs/shots", name));
    assert.ok(stat.isFile(), name + " 不是文件");
    assert.ok(stat.size > 1000, name + " 不是有效截图（体积过小）");
  }
});

test("build-dashboard.js 幂等：连跑两次产物 sha256 不变", () => {
  const script = path.join(root, "scripts/build-dashboard.js");
  const out = path.join(root, "desktop/dashboard.html");
  const before = sha256(out);

  execFileSync(process.execPath, [script], { cwd: root, encoding: "utf8" });
  const afterFirst = sha256(out);
  execFileSync(process.execPath, [script], { cwd: root, encoding: "utf8" });
  const afterSecond = sha256(out);

  assert.equal(afterFirst, before, "第一次构建不应改变内容");
  assert.equal(afterSecond, before, "第二次构建不应改变内容");
  assert.equal(sha256(out), afterSecond);
});

test("desktop/ui 源片段齐全且全部原样嵌入产物", () => {
  const uiDir = path.join(root, "desktop/ui");
  const fragments = [
    "tokens.css", "layout.css", "layout.html", "format.js",
    "charts.js", "render.js", "auth-panel.js", "app.js"
  ];
  for (const file of ["base.html", ...fragments]) {
    const stat = fs.statSync(path.join(uiDir, file));
    assert.ok(stat.isFile() && stat.size > 0, file + " 缺失或为空");
  }

  const base = read("desktop/ui/base.html");
  for (const marker of [
    "/*__TOKENS_CSS__*/", "/*__LAYOUT_CSS__*/", "<!--__LAYOUT_HTML__-->",
    "/*__FORMAT_JS__*/", "/*__CHARTS_JS__*/", "/*__RENDER_JS__*/",
    "/*__AUTH_PANEL_JS__*/", "/*__APP_JS__*/"
  ]) {
    assert.equal(base.split(marker).length - 1, 1, "占位标记 " + marker + " 应恰好出现一次");
    assert.equal(html.includes(marker), false, "构建后不应残留 " + marker);
  }
  for (const file of fragments) {
    assert.ok(html.includes(fs.readFileSync(path.join(uiDir, file), "utf8")),
      file + " 的内容应原样出现在 dashboard.html");
  }
});

test("旧版网页看板入口零残留", () => {
  for (const dead of ["openLegacy", "openPricing", "btn-legacy", "open-legacy"]) {
    assert.equal(html.includes(dead), false, "dashboard.html 不应残留 " + dead);
  }
  assert.equal(html.includes("server.js"), false, "3.0 看板不再经过本地 HTTP 服务");
});
